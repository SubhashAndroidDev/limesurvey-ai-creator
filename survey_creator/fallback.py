"""Safe offline drafts used only when the model cannot deliver after several tries.

Fallbacks preserve a question already generated by the model and provide meaningful defaults.
They never silently fill answer lists with numbered placeholders.
"""
from __future__ import annotations

import re

from .config import AppConfig, QuestionTypeSpec
from .models import Group, Question, Survey
from .schemas import GroupPlan, SurveyPlan

NOTE_AUTO = "Auto-drafted - please review"

_SCALE_QUALITY = ["Very poor", "Poor", "Fair", "Good", "Very good"]
_SCALE_AGREE = ["Strongly disagree", "Disagree", "Neither agree nor disagree", "Agree", "Strongly agree"]
_SCALE_FREQUENCY = ["Never", "Rarely", "Sometimes", "Often", "Very often"]
_SCALE_SATISFACTION = ["Very dissatisfied", "Dissatisfied", "Neither satisfied nor dissatisfied", "Satisfied", "Very satisfied"]
_PLACEHOLDER_GROUP_RE = re.compile(r"^(?:section|group|category)\s*\d+$", re.IGNORECASE)


def fallback_plan(cfg: AppConfig, request: str, group_count: int) -> SurveyPlan:
    """Minimal plan when the planner fails: title from the request, numbered sections."""
    title = " ".join(request.split())[:70].rstrip(" .,:;") or "Survey"
    pattern = str(cfg.get("survey.fallback_group_name", "Section {index}"))
    return SurveyPlan(
        title=title[:1].upper() + title[1:],
        description=f"Survey based on the request: {' '.join(request.split())[:160]}",
        welcome_text="Thank you for taking part. Your answers help us improve.",
        end_text="Thank you for your time and feedback.",
        groups=[GroupPlan(name=pattern.format(index=i + 1)) for i in range(group_count)],
    )


def _fit(items: list[str], low: int, high: int, fill_items: list[str] | None = None) -> list[str]:
    """Fit a list to configured bounds without inventing generic numbered placeholders."""
    result = list(items[:high] if high else items)
    seen = {item.casefold() for item in result}
    for candidate in fill_items or []:
        if len(result) >= low:
            break
        if candidate.casefold() not in seen:
            result.append(candidate)
            seen.add(candidate.casefold())
    # Never pad with "Option 1" when meaningful choices are unavailable. Validation
    # reports the missing entries rather than exporting misleading content.
    return result


def _fallback_topic(survey: Survey, group: Group) -> str:
    name = group.name.strip().rstrip(".")
    if name and not _PLACEHOLDER_GROUP_RE.fullmatch(name):
        return name
    request = " ".join((survey.request or survey.title).split())
    request = re.sub(r"^(?:please\s+)?(?:create|generate|build|make|design)\s+(?:a\s+)?(?:\d+[- ]question\s+)?(?:survey|questionnaire|poll)(?:\s+about|\s+for|\s+on)?\s*", "", request, flags=re.IGNORECASE)
    return request.strip(" .,:;") or survey.title or "this topic"


def _topic_options(question_text: str, topic: str) -> list[str]:
    """Return plausible choices based on the actual question text."""
    q = question_text.casefold()
    if any(word in q for word in ("age range", "how old", "your age")):
        return ["Under 18", "18–24", "25–34", "35–44", "45–54", "55 or older", "Prefer not to say"]
    if "device" in q or "devices" in q or "platform" in q:
        return ["Desktop or laptop", "Android phone", "iPhone or iPad", "Android tablet", "Other device"]
    if any(word in q for word in ("operating system", "which os", "windows, macos", "os do you")):
        return ["Windows", "macOS", "Linux", "Android", "iOS or iPadOS", "Other"]
    if any(word in q for word in ("internet connection", "connection type", "connect to the internet")):
        return ["Fiber broadband", "Cable or DSL broadband", "Mobile data", "Public Wi-Fi", "Satellite or other"]
    if any(word in q for word in ("extension", "add-on", "add on")):
        return ["Ad blocker", "Password manager", "Privacy or security tool", "Productivity tool", "Developer tool", "No extensions"]
    if any(word in q for word in ("how often", "frequency", "regularly", "how frequently")):
        return list(_SCALE_FREQUENCY)
    if any(word in q for word in ("satisfied", "satisfaction")):
        return list(_SCALE_SATISFACTION)
    if any(word in q for word in ("which feature", "features do you", "feature do you")):
        return ["Tabs", "Bookmarks", "Downloads", "Extensions", "Privacy controls", "Accessibility features", "Other"]
    return list(_SCALE_QUALITY)


def _fallback_subquestions(question_text: str, topic: str, code: str) -> list[str]:
    q = question_text.casefold()
    if "device" in q or "devices" in q or "platform" in q:
        return ["Desktop or laptop", "Android phone", "iPhone or iPad", "Tablet", "Other device"]
    if any(word in q for word in ("internet connection", "connection type")):
        return ["Fiber broadband", "Cable or DSL broadband", "Mobile data", "Public Wi-Fi", "Other connection"]
    if any(word in q for word in ("extension", "add-on", "add on")):
        return ["Ad blocking", "Password management", "Privacy and security", "Productivity", "Developer tools"]
    if any(word in q for word in ("feature", "features", "browser tool")):
        return ["Tab management", "Bookmarks", "Downloads", "Extensions", "Privacy controls"]
    if code == "Q":
        return ["Main comment", "Problem encountered", "Suggested improvement"]
    return ["Ease of use", "Reliability", "Performance", "Privacy and security", "Available features"]


def apply_fallback(survey: Survey, group: Group, question: Question, spec: QuestionTypeSpec) -> None:
    """Fill a failed question with meaningful defaults, preserving generated text when available."""
    topic = _fallback_topic(survey, group)
    topic_l = topic[:1].lower() + topic[1:]
    code = spec.code
    original_text = question.text.strip()
    answers: list[str] = []
    subs: list[str] = []

    if code == "L":
        text = original_text or f"How would you rate your overall experience with {topic_l}?"
        answers = _topic_options(text, topic)
    elif code == "M":
        text = original_text or f"Which aspects of {topic_l} matter most to you? Select all that apply."
        subs = _fallback_subquestions(text, topic, code)
    elif code == "S":
        text = original_text or f"What is the most important comment you would like to share about {topic_l}?"
    elif code == "T":
        text = original_text or f"Please describe your experience with {topic_l} and any improvements you would suggest."
    elif code == "Y":
        text = original_text or f"Have you used {topic_l}?"
    elif code == "Q":
        text = original_text or f"What details would you like to provide about {topic_l}?"
        subs = _fallback_subquestions(text, topic, code)
    elif code == "F":
        text = original_text or f"Please rate the following statements about {topic_l}."
        subs = _fallback_subquestions(text, topic, code)[:5]
        answers = list(_SCALE_AGREE)
    else:
        text = original_text or f"How satisfied are you with {topic_l}?"
        answers = list(_SCALE_SATISFACTION)

    question.text = text
    question.help = question.help or ""
    question.answers = _fit(answers, spec.answers_min, spec.answers_max, _SCALE_SATISFACTION) if spec.needs_answers else []
    question.subquestions = _fit(subs, spec.subq_min, spec.subq_max,
                                 ["Ease of use", "Reliability", "Performance", "Overall experience"]) if spec.needs_subquestions else []
    question.status, question.error, question.note = "ok", "", NOTE_AUTO
